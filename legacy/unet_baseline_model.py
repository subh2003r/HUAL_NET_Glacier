"""## *BaseLine 'UNET' model (no denoising)*"""

import numpy as np
import torch
import torch.nn as nn
import torch.optim as optim
from torch.utils.data import Dataset, DataLoader
import segmentation_models_pytorch as smp
import matplotlib.pyplot as plt
from sklearn.model_selection import train_test_split
from torchmetrics.segmentation import DiceScore
from torchmetrics import JaccardIndex

# -----------------------------
# 1. Custom Dataset class: output tensors with correct shape (C,H,W)
# -----------------------------
class GlacierDataset(Dataset):
    def __init__(self, X, Y):
        # Ensure numpy arrays are float32 dtype and contiguous in memory
        self.X = np.ascontiguousarray(X.astype(np.float32))
        self.Y = np.ascontiguousarray(Y.astype(np.float32))

    def __len__(self):
        return len(self.X)

    def __getitem__(self, idx):
        # Convert to torch tensors and permute dimensions from (H,W,C) to (C,H,W)
        img = torch.from_numpy(self.X[idx]).permute(2, 0, 1)
        mask = torch.from_numpy(self.Y[idx]).permute(2, 0, 1)
        return img, mask

train_dataset = GlacierDataset(X_train, Y_train)
val_dataset = GlacierDataset(X_val, Y_val)
test_dataset = GlacierDataset(X_test, Y_test)

train_loader = DataLoader(train_dataset, batch_size=8, shuffle=True)
val_loader = DataLoader(val_dataset, batch_size=8, shuffle=False)

# Device selection: CUDA if available
DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
print("Using device:", DEVICE)

# -----------------------------
#  Define pretrained U-Net model with ResNet34 backbone
# - Input channels are 2 for your InSAR data
# - Output classes 1 for binary segmentation (glacier vs non-glacier)
# - No activation here: sigmoid will be applied manually in loss and evaluation
# -----------------------------

model_unet = smp.Unet(
    encoder_name="resnet34",
    encoder_weights="imagenet",       # Use pretrained weights for robustness
    in_channels=X_train.shape[-1],    # Should be 2 based on your data shape (H,W,2)
    classes=1,
    activation=None
).to(DEVICE)

# -----------------------------
#  Dice Loss function definition for segmentation
# - Converts logits to probabilities internally
# - Dice coefficient is a good metric/loss for imbalanced segmentation classes
# -----------------------------

def dice_loss(pred, target, smooth=1e-6):
    pred = torch.sigmoid(pred)
    intersection = (pred * target).sum(dim=(2, 3))
    union = pred.sum(dim=(2, 3)) + target.sum(dim=(2, 3))
    dice = (2. * intersection + smooth) / (union + smooth)
    return 1 - dice.mean()

# -----------------------------
# Optimizer definition: Adam with learning rate 1e-4
# -----------------------------
optimizer = optim.Adam(model_unet.parameters(), lr=1e-4)

# -----------------------------
# Training loop over epochs
# - Tracks training loss and validation loss every epoch
# - Uses dice loss defined above
# -----------------------------

num_epochs = 150
for epoch in range(num_epochs):
    model_unet.train()  # Enable training model
    train_loss = 0.0

    for imgs, masks in train_loader:
        imgs, masks = imgs.to(DEVICE), masks.to(DEVICE)
        optimizer.zero_grad()
        outputs = model_unet(imgs)
        loss = dice_loss(outputs, masks)
        loss.backward()
        optimizer.step()
        train_loss += loss.item()

    # Validation after each training epoch
    model_unet.eval()  # Set model to eval mode for validation
    val_loss = 0.0
    with torch.no_grad():
        for imgs, masks in val_loader:
            imgs, masks = imgs.to(DEVICE), masks.to(DEVICE)
            outputs = model_unet(imgs)
            loss = dice_loss(outputs, masks)
            val_loss += loss.item()

    # Print loss statistics for monitoring
    print(f"Epoch [{epoch+1}/{num_epochs}] | Train Loss: {train_loss/len(train_loader):.4f} | Val Loss: {val_loss/len(val_loader):.4f}")

# -----------------------------
#  Evaluate on test set after training completes
# - Computes Dice score and IoU (Jaccard Index) scores
# -----------------------------
model_unet.eval()

# Initialize Dice and IoU metrics for binary segmentation
dice_metric = DiceScore(num_classes=2, average='micro').to(DEVICE)
iou_metric = JaccardIndex(task="binary").to(DEVICE)

dice_scores, iou_scores = [], []


with torch.no_grad():
    for imgs, masks in DataLoader(test_dataset, batch_size=4):
        imgs, masks = imgs.to(DEVICE), masks.to(DEVICE)
        preds = torch.sigmoid(model_unet(imgs))
        preds_bin = (preds > 0.5).int()

        # Calculate Dice and IoU scores using the metric objects
        dice_score = dice_metric(preds_bin, masks.int())
        iou_score = iou_metric(preds_bin, masks.int())

        dice_scores.append(dice_score.item())
        iou_scores.append(iou_score.item())

print(f" Dice: {np.mean(dice_scores):.3f}")
print(f"  IoU:  {np.mean(iou_scores):.3f}")

