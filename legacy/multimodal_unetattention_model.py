"""### Error map (Where the model fails)
Why this is powerful ?
1. Shows exact failure regions
2. Helps justify HUAL needs

What to compute ?
1. False positives
2. False negatives

Think of this image as a map of your model's mistakes.

-> Left: False Positives
These are places where the model said "there is glacier" but in reality there is no glacier.

** Interpretation:
1. Over segmentation
2. Often happens on shadows, rock, water or noisy SAR backscatter.

-> Middle: False Negatives
These are places where the model said "no glacier" but in reality there is glacier.

** Interpretation:
1. Under segmentation
2. Often happens on Debris-covered ice, Thin/low-contrast glacier

-> Right: Error Overlay (with color bar)
This combines both error types on one image:

Red areas = false positives (model added glacier wrongly)

Blue areas = false negatives (model missed real glacier)

White/neutral background = pixels the model got correct

"""

def visualize_error_maps(model, dataset, idx_list, threshold):
    model.eval()

    for idx in idx_list:
        img, gt = dataset[idx]
        img = img.unsqueeze(0).to(DEVICE)

        with torch.no_grad():
            pred = torch.sigmoid(model(img))
            pred = (pred >= threshold).float()

        gt_np = gt.numpy()[0]
        pred_np = pred.cpu().numpy()[0,0]
        error = pred_np - gt_np

        plt.figure(figsize=(10,3))
        plt.suptitle(f"Sample {idx}")

        plt.subplot(1,3,1)
        plt.title("False Positives")
        plt.imshow(error == 1, cmap="Reds")
        plt.axis("off")

        plt.subplot(1,3,2)
        plt.title("False Negatives")
        plt.imshow(error == -1, cmap="Blues")
        plt.axis("off")

        plt.subplot(1,3,3)
        plt.title("Error Overlay")
        plt.imshow(error, cmap="bwr")
        plt.colorbar()
        plt.axis("off")

        plt.show()


