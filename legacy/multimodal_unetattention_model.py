class GlacierDataset(Dataset):
    def __init__(self, X, Y):
        self.X = np.ascontiguousarray(X.astype(np.float32))
        self.Y = np.ascontiguousarray(Y.astype(np.float32))

    def __len__(self):
        return len(self.X)

    def __getitem__(self, idx):
        img = torch.from_numpy(self.X[idx]).permute(2, 0, 1)   # (C,H,W)
        mask = torch.from_numpy(self.Y[idx]).permute(2, 0, 1)
        return img, mask

# --------- Model -------------

def make_strong_unet(in_channels):
    """
    Multimodal-ready U-Net with SCSE attention.
    ImageNet weights are DISABLED because input channels != 3.
    """
    model = smp.Unet(
        encoder_name="resnet34",
        encoder_weights=None,          # MUST be None for 16-channel input
        in_channels=in_channels,       # e.g., 16
        classes=1,
        activation=None,
        decoder_attention_type="scse",
        encoder_depth=5,
        decoder_channels=[256,128,64,32,16]
    )
    return model.to(DEVICE)

# ------------ Loss Functions --------------

class DiceLoss(nn.Module):
    def __init__(self, smooth=1e-6):
        super().__init__()
        self.smooth = smooth

    def forward(self, logits, targets):
        probs = torch.sigmoid(logits)
        dims = (2, 3)
        intersection = (probs * targets).sum(dim=dims)
        denominator = probs.sum(dim=dims) + targets.sum(dim=dims)
        dice = (2 * intersection + self.smooth) / (denominator + self.smooth)
        return 1 - dice.mean()


bce = nn.BCEWithLogitsLoss()
dice = DiceLoss()

def combo_loss(logits, targets, alpha=0.5):
    return alpha * bce(logits, targets) + (1 - alpha) * dice(logits, targets)


# --------------- Metrics -----------------

def binarize(probs, threshold):
    return (probs >= threshold).float()

def dice_score(preds, targets, eps=1e-6):
    dims = (2,3)
    inter = (preds * targets).sum(dim=dims)
    denom = preds.sum(dim=dims) + targets.sum(dim=dims)
    return ((2*inter + eps) / (denom + eps)).mean().item()

def iou_score(preds, targets, eps=1e-6):
    dims = (2,3)
    inter = (preds * targets).sum(dim=dims)
    union = preds.sum(dim=dims) + targets.sum(dim=dims) - inter
    return ((inter + eps) / (union + eps)).mean().item()

def pixel_accuracy(preds, targets):
    return (preds == targets).float().mean().item()

# --------------- Training Validation -----------------

@torch.no_grad()
def validate_model_on_thresholds(model, validation_loader, thresholds=np.linspace(0.3, 0.7, 9)):
    model.eval()

    best_threshold = 0.5
    best_dice = -1
    best_iou = 0
    best_acc = 0

    for threshold in thresholds:
        dice_scores, iou_scores, acc_scores = [], [], []

        for images, masks in validation_loader:
            images, masks = images.to(DEVICE), masks.to(DEVICE)
            probs = torch.sigmoid(model(images))
            preds = binarize(probs, threshold)

            dice_scores.append(dice_score(preds, masks))
            iou_scores.append(iou_score(preds, masks))
            acc_scores.append(pixel_accuracy(preds, masks))

        if np.mean(dice_scores) > best_dice:
            best_dice = np.mean(dice_scores)
            best_iou = np.mean(iou_scores)
            best_acc = np.mean(acc_scores)
            best_threshold = threshold

    return best_threshold, {"dice": best_dice, "iou": best_iou, "acc": best_acc}

from typing import Dict, Any, Tuple
import time

def train_unet_model(
    train_loader: DataLoader,
    val_loader: DataLoader,
    input_channels: int,
    num_epochs: int = 150,
    learning_rate: float = 1e-4,
    weight_decay: float = 1e-4,
    validate_every: int = 3,
    best_model_save_path: str = "unet_best_glacier.pth",
    patience: int = 7,
    min_delta: float = 1e-4,
    device: str = None
) -> Dict[str, Any]:
    device = torch.device(device if device else "cuda" if torch.cuda.is_available() else "cpu")
    print(f"Training on {device}")

    model = make_strong_unet(input_channels).to(device)
    total_params = sum(p.numel() for p in model.parameters())
    trainable_params = sum(p.numel() for p in model.parameters() if p.requires_grad)
    print(f"Model: {trainable_params/1e6:.1f}M params")

    optimizer = optim.AdamW(model.parameters(), lr=learning_rate, weight_decay=weight_decay, betas=(0.9, 0.999), eps=1e-8)
    scheduler = optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=num_epochs, eta_min=learning_rate * 0.1)

    best_val_dice = -1.0
    best_threshold = 0.5
    no_improve = 0
    train_losses = []
    val_dices = []
    start_time_total = time.time()

    print("\n" + "="*80)
    print("Epoch | Train Loss | LR      | Val Dice | IoU  | Acc  | Threshold | Status")
    print("="*80)

    for epoch in range(1, num_epochs + 1):
        model.train()
        epoch_loss = 0.0
        num_batches = 0
        epoch_start = time.time()

        for batch_idx, (images, masks) in enumerate(train_loader):
            images, masks = images.to(device, non_blocking=True), masks.to(device, non_blocking=True)

            optimizer.zero_grad(set_to_none=True)
            outputs = model(images)
            loss = combo_loss(outputs, masks)

            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)
            optimizer.step()

            epoch_loss += loss.item()
            num_batches += 1

            if num_batches % 10 == 0:
                print(f"\rEpoch {epoch:02d}: [{batch_idx+1}/{len(train_loader)}] Loss: {loss.item():.4f}", end="", flush=True)

        train_loss_avg = epoch_loss / num_batches
        train_losses.append(train_loss_avg)
        scheduler.step()
        torch.cuda.empty_cache()
        train_time = time.time() - epoch_start

        if epoch % validate_every == 0 or epoch == num_epochs:
            threshold, val_stats = validate_model_on_thresholds(model, val_loader)
            val_dice = val_stats["dice"]
            val_iou = val_stats["iou"]
            val_acc = val_stats["acc"]
            val_dices.append(val_dice)

            lr = optimizer.param_groups[0]['lr']
            status = " BEST" if val_dice > best_val_dice + min_delta else "CONTINUE"

            print(f"\n{epoch:02d} | {train_loss_avg:.4f} | {lr:.2e} | "
                  f"{val_dice:.3f} | {val_iou:.3f} | {val_acc:.3f} | "
                  f"{threshold:.3f} | {status} ({train_time:.0f}s)")

            if val_dice > best_val_dice + min_delta:
                best_val_dice = val_dice
                best_threshold = threshold
                best_stats = val_stats.copy()

                torch.save({
                    'epoch': epoch,
                    'model_state_dict': model.state_dict(),
                    'optimizer_state_dict': optimizer.state_dict(),
                    'best_threshold': best_threshold,
                    'val_dice': best_val_dice,
                    'scheduler_state_dict': scheduler.state_dict()
                }, best_model_save_path)

                no_improve = 0
                print(f"  Saved new best model: Dice={val_dice:.4f}")
            else:
                no_improve += 1

        if no_improve >= patience:
            print(f"\nEarly stopping at epoch {epoch}")
            break

    total_time = time.time() - start_time_total

    print("\n" + "="*80)
    print("TRAINING COMPLETE")
    print("="*80)
    print(f"Best Validation Dice: {best_val_dice:.4f} @ threshold {best_threshold:.3f}")
    print(f"Final model saved: {best_model_save_path}")
    print(f"Total training time: {total_time:.0f}s")

    return {
        'best_model_path': best_model_save_path,
        'best_dice': best_val_dice,
        'best_threshold': best_threshold,
        'best_stats': best_stats,
        'train_losses': train_losses,
        'val_dices': val_dices,
        'final_lr': lr,
        'total_time': total_time
    }

