import torch
import numpy as np
import io

@torch.no_grad()
def test_model(ckpt_path, test_loader, in_channels):
    # Handle both file path and loaded dict
    if isinstance(ckpt_path, (str, io.BytesIO)):
        checkpoint = torch.load(ckpt_path, map_location=DEVICE, weights_only=False)  
    else:
        checkpoint = ckpt_path

    # Get threshold from results dict or checkpoint
    if 'best_model_path' in checkpoint:
        model_path = checkpoint['best_model_path']
        print(f"Loading model from: {model_path}")
        checkpoint = torch.load(model_path, map_location=DEVICE, weights_only=False)  

    best_threshold = checkpoint.get("best_threshold") or checkpoint.get("threshold", 0.5)

    model = make_strong_unet(in_channels).to(DEVICE)

    # Find state_dict key
    state_dict_key = None
    for key in ["state_dict", "model_state_dict"]:
        if key in checkpoint:
            state_dict_key = key
            break

    if state_dict_key is None:
        raise KeyError(f"No state_dict found. Checkpoint keys: {list(checkpoint.keys())}")

    model.load_state_dict(checkpoint[state_dict_key])
    model.eval()

    dices, ious, accs = [], [], []

    for imgs, masks in test_loader:
        imgs, masks = imgs.to(DEVICE), masks.to(DEVICE)
        logits = model(imgs)
        probs = torch.sigmoid(logits)
        preds = binarize(probs, best_threshold)

        dices.append(dice_score(preds, masks))
        ious.append(iou_score(preds, masks))
        accs.append(pixel_accuracy(preds, masks))

    print(f" Dice: {np.mean(dices):.3f} ± {np.std(dices):.3f}")
