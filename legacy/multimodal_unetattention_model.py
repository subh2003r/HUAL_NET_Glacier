# ---------- Utility Functions --------------

def normalize_image(image: np.ndarray) -> np.ndarray:
    """
    Normalize an image array to the range [0, 1] using min-max scaling.
    """
    x = image.astype(np.float32)
    x_min = np.min(x)
    x_max = np.max(x)
    denom = x_max - x_min + 1e-8
    normalized = (x - x_min) / denom
    return normalized


# --------- Denoising Functions -------------

def denoise_nlm_multichannel(img: np.ndarray, strength: float = 0.8) -> np.ndarray:
    """
    Apply Non-Local Means denoising to each channel of a multichannel image.
    """
    if img.ndim != 3:
        raise ValueError(
            f"Expected a 3D array (H, W, C), but got shape {img.shape}."
        )

    denoised_channels = []

    for c in range(img.shape[-1]):
        channel = img[..., c]
        sigma = np.mean(estimate_sigma(channel, channel_axis=None))
        h = strength * sigma

        denoised_channel = denoise_nl_means(
            channel,
            h=h,
            patch_size=5,
            patch_distance=6,
            fast_mode=True,
            channel_axis=None
        )
        denoised_channels.append(denoised_channel)

    denoised_img = np.stack(denoised_channels, axis=-1)

    if np.issubdtype(img.dtype, np.integer):
        info = np.iinfo(img.dtype)
        denoised_img = np.clip(denoised_img, info.min, info.max).astype(img.dtype)
    else:
        denoised_img = denoised_img.astype(img.dtype, copy=False)

    return denoised_img


# --------- Multimodal HDF5 Processing -------------

def process_hdf5_dataset(
    hdf5_path: str,
    patch_size: int = 128,
    apply_denoise: bool = True,
    min_mask_pixels: int = 10,
    max_regions: Optional[int] = 30,
) -> Tuple[np.ndarray, np.ndarray]:
    """
    Process multimodal glacier monitoring HDF5 dataset into patches for training.

    Uses per-region native spatial size (no hard-coded size).
    Can optionally limit to the first `max_regions` regions to save RAM.
    """

    # ORDER CRITICAL – must match what the model expects
    modalities = {
        "co_pol_sar": 2,
        "cross_pol_sar": 2,
        "dem": 2,
        "in_sar": 2,
        "optical": 6
    }

    TOTAL_CHANNELS = sum(modalities.values())

    X_patches: List[np.ndarray] = []
    Y_masks: List[np.ndarray] = []
    region_count = 0
    processed_regions = 0

    print(
        f"🚀 Processing {hdf5_path} | Patch size: {patch_size} | "
        f"Channels: {TOTAL_CHANNELS} | max_regions={max_regions}"
    )

    with h5py.File(hdf5_path, 'r') as f:
        region_keys = list(f.keys())
        if max_regions is not None:
            region_keys = region_keys[:max_regions]

        for region_key in region_keys:
            region = f[region_key]

            # Require outlines
            if "outlines" not in region:
                print(f"⚠️  Skipping {region_key} (no outlines)")
                continue

            print(f"📊 Processing region {region_key}...")
            processed_regions += 1

            # ----- Load mask and infer region size -----
            raw_mask = np.array(region["outlines"], dtype=np.float32)
            if raw_mask.ndim == 3:
                raw_mask = np.argmax(raw_mask, axis=-1)
            binary_mask = (raw_mask > 0).astype(np.float32)

            region_height, region_width = binary_mask.shape

            # Allocate sample tensor using region-native size
            sample = np.zeros((region_height, region_width, TOTAL_CHANNELS), dtype=np.float32)

            # ----- Fill modalities -----
            channel_offset = 0
            for modality_name, num_channels in modalities.items():
                if modality_name in region:
                    raw_data = np.array(region[modality_name], dtype=np.float32)

                    # Handle (C,H,W) → (H,W,C) if stored as (channels, height, width)
                    if raw_data.ndim == 3 and raw_data.shape[0] == num_channels:
                        raw_data = np.transpose(raw_data, (1, 2, 0))

                    # Sanity check spatial size
                    if raw_data.shape[0] != region_height or raw_data.shape[1] != region_width:
                        raise ValueError(
                            f"Spatial mismatch in region '{region_key}', modality '{modality_name}': "
                            f"expected ({region_height},{region_width}), got {raw_data.shape[:2]}"
                        )

                    # Sanity check channel count
                    if raw_data.shape[-1] != num_channels:
                        raise ValueError(
                            f"Channel mismatch in region '{region_key}', modality '{modality_name}': "
                            f"expected {num_channels} channels, got {raw_data.shape[-1]} "
                            f"(shape {raw_data.shape}). Update 'modalities' config."
                        )

                    normalized_data = normalize_image(raw_data)

                    if apply_denoise:
                        if modality_name == "in_sar":
                            normalized_data = denoise_nlm_multichannel(normalized_data, strength=0.8)
                        elif modality_name in ["co_pol_sar", "cross_pol_sar"]:
                            normalized_data = denoise_nlm_multichannel(normalized_data, strength=0.6)
                        # DEM & optical left as-is

                    sample[..., channel_offset:channel_offset + num_channels] = normalized_data
                    # Keep per-modality prints compact
                    print(f"   {modality_name}: {raw_data.shape} → OK")
                else:
                    print(f"   {modality_name}: MISSING (zero-filled)")

                channel_offset += num_channels

            # ----- Patch extraction -----
            patches_extracted = 0

            for i in range(0, region_height - patch_size + 1, patch_size // 2):  # 50% overlap
                for j in range(0, region_width - patch_size + 1, patch_size // 2):
                    img_patch = sample[i:i+patch_size, j:j+patch_size, :]
                    mask_patch = binary_mask[i:i+patch_size, j:j+patch_size]

                    glacier_pixels = np.sum(mask_patch)
                    if glacier_pixels < min_mask_pixels:
                        continue

                    X_patches.append(img_patch)
                    Y_masks.append(mask_patch[..., np.newaxis])
                    patches_extracted += 1

            if patches_extracted > 0:
                region_count += 1
                print(f"  {patches_extracted} valid patches (min_pixels={min_mask_pixels})")
            else:
                print(f"  No patches kept from region {region_key}")

    if not X_patches:
        raise ValueError(
            f"No valid patches extracted! "
            f"Check min_mask_pixels and data (processed_regions={processed_regions})."
        )

    X_train = np.stack(X_patches, axis=0).astype(np.float32)
    Y_train = np.stack(Y_masks, axis=0).astype(np.float32)

    print("\n" + "="*60)
    print("Dataset creation COMPLETE")
    print(f"{len(X_train)} patches from {region_count} regions "
          f"(processed {processed_regions} regions max)")
    print(f"Shapes → X: {X_train.shape} | Y: {Y_train.shape}")
    print(f"Memory: X={X_train.nbytes/1e9:.2f}GB, Y={Y_train.nbytes/1e9:.2f}GB")
    print("="*60)

    return X_train, Y_train


# --------- Data Splitting -------------

def split_glacier_dataset(
    X: np.ndarray,
    Y: np.ndarray,
    train_size: float = 0.7,
    val_size: float = 0.15,
    test_size: float = 0.15,
    random_state: int = 42,
    stratify: bool = True
) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    """
    Split multimodal glacier dataset into train/val/test sets.
    """

    assert X.shape[0] == Y.shape[0], "X and Y must have same number of samples"
    total_samples = X.shape[0]

    print(f" Splitting {total_samples} patches...")

    if stratify:
        glacier_ratios = np.mean(Y.reshape(total_samples, -1), axis=1)
        print(f" Glacier ratios: {glacier_ratios.min():.1%} - "
              f"{glacier_ratios.mean():.1%} - {glacier_ratios.max():.1%}")

        temp_size = 1.0 - train_size
        X_train, X_temp, Y_train, Y_temp = train_test_split(
            X, Y,
            test_size=temp_size,
            random_state=random_state,
            shuffle=True
        )

        X_val, X_test, Y_val, Y_test = train_test_split(
            X_temp, Y_temp,
            test_size=0.5,
            random_state=random_state,
            shuffle=True
        )
    else:
        X_temp, X_test, Y_temp, Y_test = train_test_split(
            X, Y, test_size=test_size, random_state=random_state, shuffle=True
        )
        X_train, X_val, Y_train, Y_val = train_test_split(
            X_temp, Y_temp,
            test_size=val_size / (train_size + val_size),
            random_state=random_state,
            shuffle=True
        )

    def glacier_stats(masks: np.ndarray) -> str:
        ratios = np.mean(masks.reshape(masks.shape[0], -1), axis=1)
        return f"N={len(masks)} | Glacier: {np.mean(ratios):.1%} ± {np.std(ratios):.1%}"

    print("\n" + "="*70)
    print("DATA SPLIT COMPLETE")
    print("="*70)
    print(f"{'Split':<8} {'Shape':<20} {'Samples':<8} {'Glacier Coverage'}")
    print("-"*70)
    print(f"{'Train':<8} {str(X_train.shape):<20} {len(X_train):<8} {glacier_stats(Y_train)}")
    print(f"{'Val':<8}   {str(X_val.shape):<20} {len(X_val):<8} {glacier_stats(Y_val)}")
    print(f"{'Test':<8}  {str(X_test.shape):<20} {len(X_test):<8} {glacier_stats(Y_test)}")
    print("-"*70)
    print(f"Total: {total_samples} → {len(X_train)}/{len(X_val)}/{len(X_test)}")

    mem_gb = lambda arr: f"{arr.nbytes/1e9:.2f}GB"
    print(f"\n Memory → Train: {mem_gb(X_train):>8}, "
          f"Val: {mem_gb(X_val):>8}, Test: {mem_gb(X_test):>8}")

    return X_train, X_val, X_test, Y_train, Y_val, Y_test


