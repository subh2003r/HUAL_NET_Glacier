import numpy as np
import h5py

def process_hdf5_dataset(hdf5_path, patch_size=128):
    """
    Processes an InSAR HDF5 dataset into small patches for segmentation.
    Each region must contain 'in_sar' and 'outlines' datasets.

    Args:
        hdf5_path (str): Path to the HDF5 dataset.
        patch_size (int): Size of patches to extract (default=128).

    Returns:
        X (np.ndarray): Input image patches, shape (N, patch_size, patch_size, C)
        Y (np.ndarray): Mask patches, shape (N, patch_size, patch_size, 1)
    """
    X_list, Y_list = [], []
    region_count = 0  # To count valid regions with data

    with h5py.File(hdf5_path, 'r') as f:
        region_keys = [k for k in f.keys() if "in_sar" in f[k] and "outlines" in f[k]]
        for key in region_keys:
            region = f[key]

            # read arrays
            img = np.array(region["in_sar"])       # shape (H, W, C)
            mask = np.array(region["outlines"])    # shape (H, W, [classes])

            # normalize input to [0,1]
            img = (img - np.min(img)) / (np.max(img) - np.min(img) + 1e-8)

            # if mask is one-hot (H, W, 2) -> convert to binary (H, W)
            if mask.ndim == 3:
                mask = np.argmax(mask, axis=-1)

            mask = mask.astype(np.float32)
            H, W = mask.shape

            found_patch = False
            # extract non-overlapping patches
            for i in range(0, H - patch_size + 1, patch_size):
                for j in range(0, W - patch_size + 1, patch_size):
                    patch_img = img[i:i+patch_size, j:j+patch_size, :]
                    patch_mask = mask[i:i+patch_size, j:j+patch_size]

                    # skip empty patches (optional)
                    if np.sum(patch_mask) < 10:
                        continue

                    X_list.append(patch_img)
                    Y_list.append(patch_mask[..., np.newaxis])  # add channel
                    found_patch = True  # At least one patch found in this region

            if found_patch:
                region_count += 1

        # Print statement moved inside the 'with' block
        print(f"✅ Processed {len(X_list)} patches from {region_count} regions.")

    # stack into final numpy arrays (after file is closed)
    X = np.stack(X_list, axis=0)
    Y = np.stack(Y_list, axis=0)
    print(f"Final shapes -> X: {X.shape}, Y: {Y.shape}")

    return X, Y

# Usage
X, Y = process_hdf5_dataset(hdf5_path, patch_size=128)
